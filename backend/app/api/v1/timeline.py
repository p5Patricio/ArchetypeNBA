def get_timeline(
    era_id: Optional[str] = Query(default=None, description="Filtrar por ID de era (ej: era_foundation, era_modern_empowerment)"),
    category: Optional[str] = Query(default=None, description="Filtrar por categoría (milestones, scandals_brawls, culture_rules, legendary_games, dynasties)"),
    q: Optional[str] = Query(default=None, description="Término de búsqueda de texto"),
):
    actual_era = era_id if isinstance(era_id, str) else None
    actual_category = category if isinstance(category, str) else None
    actual_q = q if isinstance(q, str) else None

    events = TIMELINE_EVENTS

    if actual_era and actual_era != "all":
        events = [e for e in events if e.era_id == actual_era]

    if actual_category and actual_category != "all":
        events = [e for e in events if e.category == actual_category]

    if actual_q and actual_q.strip():
        term = actual_q.strip().lower()
        events = [
            e for e in events
            if term in e.title_es.lower()
            or term in e.title_en.lower()
            or term in e.headline_es.lower()
            or term in e.headline_en.lower()
            or term in e.description_es.lower()
            or term in e.description_en.lower()
            or any(term in actor.lower() for actor in e.key_actors)
            or any(term in tag.lower() for tag in e.tags)
            or str(e.year) in term
        ]

    # Orden cronológico por año
    events = sorted(events, key=lambda x: (x.year, x.exact_date or ""))

    return TimelineResponse(
        eras=TIMELINE_ERAS,
        categories=TIMELINE_CATEGORIES,
        total_events=len(events),
        events=events,
    )
