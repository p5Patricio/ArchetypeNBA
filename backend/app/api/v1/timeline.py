from typing import Optional, List
from fastapi import APIRouter, Query
from pydantic import BaseModel

router = APIRouter()


class TimelineEra(BaseModel):
    id: str
    name_es: str
    name_en: str
    year_range: str
    summary_es: str
    summary_en: str
    color: str


class TimelineEvent(BaseModel):
    id: str
    year: int
    exact_date: Optional[str] = None
    era_id: str
    category: str  # "milestones" | "scandals_brawls" | "culture_rules" | "legendary_games" | "dynasties"
    title_es: str
    title_en: str
    headline_es: str
    headline_en: str
    description_es: str
    description_en: str
    key_actors: List[str]
    impact_summary_es: str
    impact_summary_en: str
    tags: List[str]
    icon_type: str  # "trophy" | "flame" | "shirt" | "sword" | "crown" | "scale"
    severity: Optional[str] = None  # "historic" | "controversy" | "fine" | "suspension" | "revolution"
    trivia_es: Optional[str] = None
    trivia_en: Optional[str] = None
    media_badge: Optional[str] = None
    image_url: Optional[str] = None
    image_caption: Optional[str] = None
    player_headshot: Optional[str] = None


class TimelineResponse(BaseModel):
    eras: List[TimelineEra]
    categories: List[dict]
    total_events: int
    events: List[TimelineEvent]


